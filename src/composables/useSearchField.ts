/**
 * useSearchField —— 搜索输入框的正确绑定方式
 *
 * ---------------------------------------------------------------------------
 * 【为什么不用 `:value` + `@input`】
 * 那是「受控输入」写法：输入框的显示值**完全由模型决定**。
 * 问题在于：一旦框架把模型值回写到 DOM，浏览器就会**重置光标位置** ——
 * 这是浏览器的行为，不是框架的 bug，但它的后果很难受：
 *
 *   反向选中一段文字（鼠标从右往左拖，selectionDirection 为 backward），
 *   然后直接打字时，光标会被复位到选区**左端**，
 *   后面每个字符都插到前一个字符前面 ——
 *   于是「输入 1234」看起来变成了「4321」。
 *
 * ---------------------------------------------------------------------------
 * 【这里的做法】
 * 输入框由**本地 ref** 驱动（`v-model`），模型只在真正需要时（外部改了条件）才回写。
 * 打字过程中**不存在任何回写**，光标不会被碰 —— 这类问题从根上不会发生。
 *
 * 这是一次**结构性加固**：把「会在打字时回写」的写法换掉，
 * 而不是去猜某一次具体是在什么时机被回写的。
 * ---------------------------------------------------------------------------
 */
import { ref, watch, type Ref } from 'vue'

export function useSearchField(source: Ref<string>, commit: (value: string) => void): Ref<string> {
  /** 输入框的值。打字时只改它，不回写 */
  const text = ref(source.value)

  // 打字方向：本地 → 模型
  watch(text, (next) => commit(next))

  // 外部改了条件（例如「清除全部条件」）→ 同步回输入框
  watch(source, (next) => {
    if (next !== text.value) text.value = next
  })

  return text
}
